// Writes public/blur-placeholders.css: a tiny blurred copy of every photo in public/images, so a photo
// fades in over its own colours instead of a grey box (components/ui/blur-image.tsx sets
// data-blur="<src>" on its placeholder and adds this stylesheet after the first paint). A static
// stylesheet rather than a JS map: it loads once, off the critical path, instead of being copied
// into every route chunk that shows a photo.
// 4 x 4 px WebP: under the 12 px CSS blur it reads exactly like an 8 px one, at two thirds of the
// bytes (46 photos, about 1.7 kB gzipped).
//
//   node scripts/blur-placeholders.mjs        (also run by `npm run build`)
//
// sharp comes with Next.js. Without it this keeps the committed file and says so.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SIZE = 4;

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.warn("blur-placeholders: sharp is not available; keeping public/blur-placeholders.css as it is.");
  process.exit(0);
}

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(jpe?g|png|webp)$/i.test(name)) files.push(p);
  }
})(path.join(root, "public/images"));

const rules = [];
for (const file of files) {
  const buf = await sharp(file).resize(SIZE, SIZE, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  const src = `/${path.relative(path.join(root, "public"), file).split(path.sep).join("/")}`;
  rules.push(`[data-blur="${src}"] {\n  background-image: url(data:image/webp;base64,${buf.toString("base64")});\n}`);
}

writeFileSync(
  path.join(root, "public/blur-placeholders.css"),
  `/* Generated by scripts/blur-placeholders.mjs from public/images (npm run blur). Do not edit by hand. */\n${rules.join("\n")}\n`,
);
console.log(`blur-placeholders: ${files.length} photos`);
