// Writes lib/blur-placeholders.ts: a tiny blurred copy of every photo in public/images, so a photo
// fades in over its own colours instead of a grey box (components/ui/blur-image.tsx).
// 4 x 4 px WebP: under the 12 px CSS blur it reads exactly like an 8 px one, at two thirds of the
// bytes (all of them ship with the shop: 46 photos, about 1.7 kB gzipped).
//
//   node scripts/blur-placeholders.mjs        (also run by `npm run build`)
//
// sharp comes with Next.js. Without it this keeps the committed file and says so.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SIZE = 4;

let sharp;
try {
  sharp = (await import("sharp")).default;
} catch {
  console.warn("blur-placeholders: sharp is not available; keeping lib/blur-placeholders.ts as it is.");
  process.exit(0);
}

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(jpe?g|png|webp)$/i.test(name)) files.push(p);
  }
})(path.join(root, "public/images"));

const lines = [];
for (const file of files) {
  const buf = await sharp(file).resize(SIZE, SIZE, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  lines.push(`  "/${path.relative(path.join(root, "public"), file).split(path.sep).join("/")}": "data:image/webp;base64,${buf.toString("base64")}",`);
}

writeFileSync(
  path.join(root, "lib/blur-placeholders.ts"),
  `// Generated by scripts/blur-placeholders.mjs from public/images. Do not edit by hand.
const BLUR: Record<string, string> = {
${lines.join("\n")}
};

/** The blurred placeholder for a photo in public/images, if there is one. */
export const blurFor = (src: string): string | undefined => BLUR[src];

export const blurredImages = () => Object.keys(BLUR);
`,
);
console.log(`blur-placeholders: ${files.length} photos`);
