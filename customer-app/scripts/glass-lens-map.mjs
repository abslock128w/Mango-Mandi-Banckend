// Writes components/glass/lens-map.ts: the edge map behind the liquid glass lens (docs/design/
// shop-motion.md, "Liquid glass"). A 32 x 32 PNG whose red and green channels are the x and y
// displacement feDisplacementMap reads: 128 (no shift) in the clear centre, rising towards the
// nearest edge and pointing at it, so the backdrop stretches at the rim the way light bends at the
// edge of a lens. Stretched over each glass element by feImage (preserveAspectRatio none).
//
//   node scripts/glass-lens-map.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const N = 32;
// Where the rim starts, as a fraction of the half-width: inside it the glass is clear.
const CLEAR = 0.62;

const crc = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return (buf) => {
    let c = -1;
    for (const b of buf) c = t[(c ^ b) & 0xff] ^ (c >>> 8);
    return (c ^ -1) >>> 0;
  };
})();
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const c = Buffer.alloc(4);
  c.writeUInt32BE(crc(td));
  return Buffer.concat([len, td, c]);
};

const raw = Buffer.alloc((N * 3 + 1) * N);
for (let y = 0; y < N; y++) {
  raw[y * (N * 3 + 1)] = 0; // filter: none
  for (let x = 0; x < N; x++) {
    // -1..1 across the element, measured from the centre of each pixel.
    const u = ((x + 0.5) / N) * 2 - 1;
    const v = ((y + 0.5) / N) * 2 - 1;
    // How far into the rim band we are on each axis (0 in the clear centre, 1 at the edge), eased.
    const ease = (t) => t * t * (3 - 2 * t);
    const rx = ease(Math.min(1, Math.max(0, (Math.abs(u) - CLEAR) / (1 - CLEAR))));
    const ry = ease(Math.min(1, Math.max(0, (Math.abs(v) - CLEAR) / (1 - CLEAR))));
    // Displacement points at the nearer edge, strongest at the rim.
    const dx = Math.sign(u) * rx;
    const dy = Math.sign(v) * ry;
    const o = y * (N * 3 + 1) + 1 + x * 3;
    raw[o] = Math.round(128 + dx * 120);
    raw[o + 1] = Math.round(128 + dy * 120);
    raw[o + 2] = 128;
  }
}
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(N, 0);
ihdr.writeUInt32BE(N, 4);
ihdr[8] = 8; // bit depth
ihdr[9] = 2; // RGB
const png = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../components/glass/lens-map.ts");
writeFileSync(
  out,
  `// Generated by scripts/glass-lens-map.mjs: the ${N} x ${N} edge map the liquid glass lens displaces by. Do not edit.\nexport const LENS_MAP = "data:image/png;base64,${png.toString("base64")}";\n`,
);
console.log(`${out}: ${png.length} B`);
