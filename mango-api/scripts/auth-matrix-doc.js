#!/usr/bin/env node
// Writes docs/authorization-matrix.md: who may call each staff route, which ones ask the
// manager to confirm it is them (step-up), and which are written to the staff audit.
//
//   node scripts/auth-matrix-doc.js
//
// It reads the reviewed role snapshot (test/fixtures/role-policy.json) and admin/policy.js.
// Run it after a change to either and commit the result; test/auth-matrix.test.js fails
// while the committed doc is out of date.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { ALWAYS_AUDITED_READS, READ_AUDITED_ROUTES, STEP_UP_ROUTES } from '../src/admin/policy.js'

const ROLES = ['MANAGER', 'OPERATOR', 'PACKER', 'QC', 'RIDER']
const ROLE_NAMES = { MANAGER: 'Manager', OPERATOR: 'Operator', PACKER: 'Packer', QC: 'QC', RIDER: 'Rider' }
export const POLICY_FILE = new URL('../test/fixtures/role-policy.json', import.meta.url)
export const DOC_FILE = new URL('../../docs/authorization-matrix.md', import.meta.url)

/** The panel area a route belongs to, by its first path segment. */
const AREAS = [
  ['Your account', ['auth', 'me']],
  ['Staff and settings', ['staff', 'audit', 'settings']],
  ['Orders and deliveries', ['orders', 'gift-orders', 'pack-list', 'manifest', 'riders', 'delivery-reviews']],
  ['Batches, farms and purchases', ['batches', 'farms', 'purchases']],
  ['Products', ['products']],
  ['Promo codes and referrals', ['promos', 'referrals']],
  ['Bulk deals', ['bulk-listings']],
  ['Preorders', ['preorders', 'preorder-capacity']],
  ['Planning', ['planning', 'pincodes', 'config', 'calendar', 'slots', 'coverage']],
  ['Customer care', ['claims', 'reviews', 'help', 'subscriptions', 'customers']],
  ['Reports', ['summary', 'analytics', 'attention', 'daily-summary', 'exports']],
  ['Recovery', ['webhook-failures', 'refunds', 'notifications']],
  ['Warehouse', ['warehouse']],
]
const areaOf = (route) => {
  const segment = route.split(' ')[1].split('/')[1]
  return AREAS.find(([, segments]) => segments.includes(segment))?.[0] ?? 'Other'
}

const STEP_UP = new Map(STEP_UP_ROUTES.map((r) => [r.route, r]))

function stepUpCell(route) {
  const s = STEP_UP.get(route)
  if (!s) return ''
  return `${s.always ? 'Always' : 'With STAFF_STEP_UP'}: ${s.when.charAt(0).toLowerCase()}${s.when.slice(1)}`
}

function auditCell(route) {
  if (!route.startsWith('GET ')) return 'Each change'
  if (ALWAYS_AUDITED_READS.includes(route)) return 'Each view'
  if (READ_AUDITED_ROUTES.includes(route)) return 'Views (STAFF_AUDIT_TRAIL)'
  if (route === 'GET /orders') return 'Searches (STAFF_AUDIT_TRAIL)'
  return ''
}

const code = (s) => `\`${s}\``

/** The doc for this policy. Pure, so the test can compare it with the committed file. */
export function renderMatrix(policy = JSON.parse(readFileSync(POLICY_FILE, 'utf8'))) {
  const routes = Object.keys(policy)
  for (const s of STEP_UP_ROUTES) if (!policy[s.route]) throw new Error(`${s.route} is in STEP_UP_ROUTES but not in the role policy`)
  const out = [
    '# Staff authorization matrix',
    '',
    '<!-- Generated by mango-api/scripts/auth-matrix-doc.js. Do not edit by hand: run `node scripts/auth-matrix-doc.js` in mango-api. -->',
    '',
    'Who may call each staff route (`/admin/v1`), which routes ask the manager to confirm it is them, and what is written to the staff audit.',
    'It is generated from the reviewed role snapshot (`mango-api/test/fixtures/role-policy.json`) and `mango-api/src/admin/policy.js`.',
    '`test/auth-matrix.test.js` calls every route as every role and fails if this file is out of date.',
    '',
    '- **Roles.** ✓ means the role may call the route. Every other role gets 403. Managers may call everything.',
    '- **Step-up.** The manager confirms with their two-step code, or their password if two-step is off (`confirmCode` in the body).',
    '  "Always" routes ask even with `STAFF_STEP_UP` off; the rest ask with it on, the default in production. Only the requests described ask.',
    '- **Audit.** Every successful change is written to `staff_audit` (who, route, target, body without secrets). The table is append-only.',
    '  Views marked here record who looked at customer details. See [authorization.md](authorization.md).',
    '',
    `${routes.length} routes; ${STEP_UP_ROUTES.length} ask for step-up.`,
  ]
  const byArea = new Map(AREAS.map(([name]) => [name, []]).concat([['Other', []]]))
  for (const r of routes) byArea.get(areaOf(r)).push(r)
  for (const [area, list] of byArea) {
    if (!list.length) continue
    out.push('', `## ${area}`, '', `| Route | ${ROLES.map((r) => ROLE_NAMES[r]).join(' | ')} | Step-up | Audit |`, `|---|${ROLES.map(() => ':-:').join('|')}|---|---|`)
    for (const r of list.sort((a, b) => a.split(' ')[1].localeCompare(b.split(' ')[1]) || a.localeCompare(b))) {
      out.push(`| ${code(r)} | ${ROLES.map((role) => (policy[r].includes(role) ? '✓' : '')).join(' | ')} | ${stepUpCell(r)} | ${auditCell(r)} |`)
    }
  }
  return `${out.join('\n')}\n`
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(DOC_FILE, renderMatrix())
  console.log(`Wrote ${fileURLToPath(DOC_FILE)}`)
}
